// Generates supabase/seed.sql from supabase/seed/foods.data.ts and sanity-checks the data.
// Run: npm run seed:gen   (Node 25 runs TypeScript directly)
import { readFileSync, writeFileSync } from "node:fs";
import { FOODS } from "../supabase/seed/foods.data.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const norm = (s: string) => s.normalize("NFKD").toLowerCase().trim();
const warnings: string[] = [];

const seen = new Map<string, string>();
const ids = new Set<string>();
for (const [key, name, variant, aliases, , , , kcal, p, c, f] of FOODS) {
  const id = `${key}/${variant ?? ""}`;
  if (ids.has(id)) warnings.push(`duplicate row ${id}`);
  ids.add(id);

  const fromMacros = p * 4 + c * 4 + f * 9;
  if (kcal > 20 && Math.abs(fromMacros - kcal) / kcal > 0.2) warnings.push(`macros≠kcal for ${name}: stated ${kcal}, macros give ${Math.round(fromMacros)}`);

  for (const a of new Set([...aliases, name].map(norm))) {
    const prev = seen.get(a);
    if (prev && prev !== key) warnings.push(`alias "${a}" claimed by both ${prev} and ${key}`);
    seen.set(a, key);
  }
}

const values = FOODS.map(([key, name, variant, aliases, desc, unit, grams, kcal, p, c, f]) => {
  const al = `array[${[...new Set(aliases.map((a) => a.toLowerCase()))].map(q).join(",")}]::text[]`;
  return `  (${q(key)}, ${q(name)}, ${variant ? q(variant) : "null"}, ${al}, ${q(desc)}, ${q(unit)}, ${grams ?? "null"}, ${kcal}, ${p}, ${c}, ${f}, 'curated_estimate', 'Typical serving estimate; pending IFCT 2017 verification')`;
});

// ───── IFCT 2017 (ICMR-NIN) raw ingredients, per 100 g edible portion ─────
function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n") { row.push(cell.replace(/\r$/, "")); rows.push(row); row = []; cell = ""; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.length > 1);
}

const slug = (s: string) => s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");
const [hdr, ...ifctRows] = parseCsv(readFileSync(new URL("../supabase/seed/ifct2017.csv", import.meta.url), "utf8"));
const col = (r: string[], k: string) => Number(r[hdr.indexOf(k)]);
const seenIfct = new Set<string>();
const ifctValues: string[] = [];
let ifctSkipped = 0;
for (const r of ifctRows) {
  const code = r[hdr.indexOf("code")], name = r[hdr.indexOf("name")].trim();
  const kcal = Math.round(col(r, "enerc") / 4.184);
  if (!(kcal > 0)) { ifctSkipped++; continue; } // oils/ghee are listed without energy in IFCT
  // "Tomato, ripe, local" -> dish "tomato", variant "ripe, local" so ambiguity becomes a button prompt
  const [base, ...rest] = name.split(",");
  const key = `ifct_${slug(base)}`;
  let variant = rest.join(",").trim().toLowerCase() || null;
  const id = `${key}/${variant ?? ""}`;
  if (seenIfct.has(id)) variant = `${variant ?? "plain"} (${code.toLowerCase()})`;
  seenIfct.add(`${key}/${variant ?? ""}`);
  const num = (k: string) => Math.round(col(r, k) * 10) / 10 || 0;
  ifctValues.push(`  (${q(key)}, ${q(name)}, ${variant ? q(variant) : "null"}, array[${q(name.toLowerCase())}]::text[], '100 g (edible portion)', 'g', 100, ${kcal}, ${num("protcnt")}, ${num("choavldf")}, ${num("fatce")}, 'ifct2017', ${q(`IFCT 2017 ${code}`)})`);
}

const sql = `-- GENERATED by scripts/gen-seed.ts from supabase/seed/foods.data.ts — do not edit by hand.
insert into public.foods
  (food_key, name, variant, aliases, serving_desc, serving_unit, serving_grams, kcal, protein_g, carbs_g, fat_g, source, source_ref)
values
${[...values, ...ifctValues].join(",\n")}
on conflict (food_key, (coalesce(variant, ''))) where user_id is null do update set
  name = excluded.name, aliases = excluded.aliases, serving_desc = excluded.serving_desc, serving_unit = excluded.serving_unit,
  serving_grams = excluded.serving_grams, kcal = excluded.kcal, protein_g = excluded.protein_g, carbs_g = excluded.carbs_g,
  fat_g = excluded.fat_g, source = excluded.source, source_ref = excluded.source_ref;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`${FOODS.length} curated rows + ${ifctValues.length} IFCT rows (${ifctSkipped} skipped: no energy value) → supabase/seed.sql`);
if (warnings.length) console.log("\nWARNINGS:\n" + warnings.map((w) => " - " + w).join("\n"));
